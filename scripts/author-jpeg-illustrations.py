"""Author eight CC0 river landscapes; Pillow is an authoring tool, not a runtime dependency."""
import base64
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageDraw

assets = []
for index in range(8):
    image = Image.new("RGB", (96, 72), (220, 236, 245))
    draw = ImageDraw.Draw(image)
    draw.ellipse((62-index*3, 6, 76-index*3, 20), fill=(248, 212, 110))
    draw.polygon([(0, 38), (20, 22+index), (44, 41), (70, 24), (95, 39), (95, 71), (0, 71)], fill=(82, 131, 108))
    draw.polygon([(35+index, 38), (48+index, 38), (82, 71), (12, 71)], fill=(73, 148, 185))
    left = 8 + index * 2
    draw.rectangle((left, 38, left+15, 51), fill=(233, 205, 162))
    draw.polygon([(left-2, 38), (left+7, 29), (left+17, 38)], fill=(131, 79, 66))
    draw.rectangle((left+6, 43, left+10, 51), fill=(65, 67, 65))
    for tree in range(3):
        x = 63 + tree*10
        draw.line((x, 43, x, 59+index), fill=(78, 71, 54), width=2)
        draw.ellipse((x-5, 33+tree, x+6, 47+tree), fill=(37+index*3, 98, 65))
    buffer = BytesIO()
    image.save(buffer, "JPEG", quality=78, optimize=False, progressive=False, subsampling=0)
    assets.append(base64.b64encode(buffer.getvalue()).decode("ascii"))
target = Path(__file__).resolve().parents[1] / "src/core/datasets/original-jpeg-data.ts"
target.write_text("// Generated by scripts/author-jpeg-illustrations.py. Original illustrations, CC0-1.0.\nexport const originalJpegBase64: readonly string[] = [\n" + "".join("  '" + asset + "',\n" for asset in assets) + "];\n", encoding="utf-8")
print(f"Authored {len(assets)} original JPEG illustrations.")
