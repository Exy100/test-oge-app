/** Twelve authored sets exercise the three observed document layouts. */
export const documentSets: readonly DocumentSet[] = materials.map(
  (set, index) => {
    const family =
      (['description', 'instructions', 'sections'] as const)[index % 3] ??
      'description';
    const pairs = set.rows.map(
      (row) => [row[0] ?? '', row.slice(1).join(' — ')] as const,
    );
    const count = family === 'sections' ? 7 : family === 'instructions' ? 3 : 4;
    const rows = [
      ...pairs,
      ...(extraRows[set.id] ?? [['Контроль', 'Повторная проверка результата']]),
    ].slice(0, count);
    return {
      id: set.id,
      title: set.title.toLocaleUpperCase('ru-RU'),
      family,
      sectionTitle: 'Дополнительные сведения',
      paragraphs: [
        set.paragraphs[0] ?? '',
        `${set.paragraphs[1] ?? ''} ${details[index] ?? ''}`,
      ],
      headers:
        family === 'instructions'
          ? ['Этап', 'Действие']
          : ['Основные сведения'],
      rows,
      format: {
        bodySize: 14,
        lineHeight: set.lineHeight === 150 ? 150 : 115,
        titleAlign: 'center',
        bodyAlign: 'justify',
        indent: 1,
        widths: [7, 8],
        headerColor: '#FFFFFF',
      },
    };
  },
);
